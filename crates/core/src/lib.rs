//! Domain: what it means to publish a version, who can do it, and when it is available.
//! It does not depend on NuGet, SQLx, or Axum (ADR-003).

pub mod auth;

use std::fmt;

pub use auth::{
    Access, AuthContext, Denial, Grant, Principal, PrincipalKind, PrincipalName, PublishPattern,
    Role,
};

/// Feed name: `[a-z0-9-]`, 1 to 64 characters, starts with a letter or digit.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct FeedName(String);

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InvalidFeedName(pub String);

impl fmt::Display for InvalidFeedName {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "invalid feed name: {:?} (use a-z, 0-9 and '-', at most 64, starting with a letter or digit)",
            self.0
        )
    }
}

impl std::error::Error for InvalidFeedName {}

impl FeedName {
    pub const MAX_LEN: usize = 64;

    pub fn parse(input: &str) -> Result<Self, InvalidFeedName> {
        let valid = (1..=Self::MAX_LEN).contains(&input.len())
            && input
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
            && !input.starts_with('-');
        if valid {
            Ok(Self(input.to_owned()))
        } else {
            Err(InvalidFeedName(input.to_owned()))
        }
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for FeedName {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// Existing feed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Feed {
    pub id: i64,
    pub name: FeedName,
}

/// Version to publish, already validated by the format adapter.
///
/// The identity within the feed is `package_key + version_key` (ADR-007); the adapter decides
/// how they are normalized, and the domain only requires that they do not repeat.
#[derive(Debug, Clone)]
pub struct NewVersion {
    /// Id as written by the author.
    pub package_id: String,
    pub package_key: String,
    /// Normalized version, with the original capitalization.
    pub version: String,
    pub version_key: String,
    /// Full version, with build metadata if present.
    pub full_version: String,
    pub is_prerelease: bool,
    pub is_semver2: bool,
    /// JSON metadata document generated by the adapter; the domain does not interpret it.
    pub metadata: String,
    /// Lowercase text to search on.
    pub search_text: String,
}

impl NewVersion {
    /// Human-readable resource for auditing and messages: `Id@version`.
    pub fn resource(&self) -> String {
        format!("{}@{}", self.package_id, self.version)
    }
}

/// Published version.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PublishedVersion {
    pub package_id: String,
    pub package_key: String,
    pub version: String,
    pub version_key: String,
    pub full_version: String,
    pub is_prerelease: bool,
    pub is_semver2: bool,
    pub blob_sha256: String,
    pub size: u64,
    pub listed: bool,
    /// `availability: blocked` (ADR-013): it remains in the metadata, but is not downloaded.
    pub blocked: bool,
    /// RFC 3339 (UTC).
    pub published_at: String,
    pub metadata: Option<String>,
    pub search_text: Option<String>,
}

/// Feed quotas (ADR-014). `None` means no limit.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct FeedQuota {
    pub max_storage_bytes: Option<u64>,
    pub max_versions: Option<u64>,
}

/// Feed usage: logical sum of the sizes of its versions.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct FeedUsage {
    pub versions: u64,
    pub storage_bytes: u64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum QuotaKind {
    Versions,
    Storage,
}

impl QuotaKind {
    pub fn code(self) -> &'static str {
        match self {
            Self::Versions => "FEED_QUOTA_VERSIONS",
            Self::Storage => "FEED_QUOTA_STORAGE",
        }
    }
}

impl FeedQuota {
    /// Quota that would be exceeded when adding a version of `size` bytes.
    pub fn exceeded_by(&self, usage: FeedUsage, size: u64) -> Option<QuotaKind> {
        if self
            .max_versions
            .is_some_and(|max| usage.versions + 1 > max)
        {
            Some(QuotaKind::Versions)
        } else if self
            .max_storage_bytes
            .is_some_and(|max| usage.storage_bytes.saturating_add(size) > max)
        {
            Some(QuotaKind::Storage)
        } else {
            None
        }
    }
}

#[derive(Debug)]
pub enum PublishError {
    /// The identity already exists. `identical` indicates whether the content matches byte for byte, which
    /// allows a client to treat the duplicate as a success explicitly (ADR-007).
    Conflict {
        identical: bool,
    },
    /// Publishing it would exceed a feed quota; nothing is persisted.
    QuotaExceeded(QuotaKind),
    StorageFull,
    Io(std::io::Error),
    Database(String),
}

impl fmt::Display for PublishError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Conflict { identical: true } => {
                f.write_str("the version already exists with the same content")
            }
            Self::Conflict { identical: false } => {
                f.write_str("the version already exists with different content")
            }
            Self::QuotaExceeded(kind) => write!(f, "{}: feed quota exceeded", kind.code()),
            Self::StorageFull => f.write_str("storage is out of space"),
            Self::Io(e) => write!(f, "I/O error: {e}"),
            Self::Database(e) => write!(f, "database error: {e}"),
        }
    }
}

impl std::error::Error for PublishError {}

impl From<std::io::Error> for PublishError {
    fn from(e: std::io::Error) -> Self {
        if e.kind() == std::io::ErrorKind::StorageFull {
            Self::StorageFull
        } else {
            Self::Io(e)
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quotas() {
        let usage = FeedUsage {
            versions: 2,
            storage_bytes: 100,
        };
        assert_eq!(FeedQuota::default().exceeded_by(usage, u64::MAX), None);
        let versions = FeedQuota {
            max_versions: Some(3),
            ..FeedQuota::default()
        };
        assert_eq!(versions.exceeded_by(usage, 1), None);
        let full = FeedUsage {
            versions: 3,
            ..usage
        };
        assert_eq!(versions.exceeded_by(full, 1), Some(QuotaKind::Versions));
        let storage = FeedQuota {
            max_storage_bytes: Some(150),
            ..FeedQuota::default()
        };
        assert_eq!(storage.exceeded_by(usage, 50), None);
        assert_eq!(storage.exceeded_by(usage, 51), Some(QuotaKind::Storage));
    }

    #[test]
    fn feed_names() {
        for ok in ["internal", "customer-a", "a", "x1", &"a".repeat(64)] {
            assert!(FeedName::parse(ok).is_ok(), "{ok}");
        }
        for bad in [
            "",
            "-a",
            "Internal",
            "a_b",
            "a b",
            "a/b",
            "..",
            &"a".repeat(65),
        ] {
            assert!(FeedName::parse(bad).is_err(), "{bad}");
        }
    }
}
